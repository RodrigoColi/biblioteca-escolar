CREATE TABLE alunos (
    matricula INTEGER      PRIMARY KEY,
    nome      VARCHAR(100) NOT NULL,
    email     VARCHAR(100) NOT NULL,
    turma     VARCHAR(20)  NOT NULL
);

CREATE TABLE livros (
    id_livro       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(150) NOT NULL,
    autor          VARCHAR(100) NOT NULL,
    genero         VARCHAR(50)  NOT NULL,
    ano_publicacao INTEGER      NOT NULL
);

CREATE TABLE emprestimos (
    id_emprestimo   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula       INTEGER NOT NULL REFERENCES alunos (matricula),
    id_livro        INTEGER NOT NULL REFERENCES livros (id_livro),
    data_emprestimo DATE    NOT NULL,
    data_prevista   DATE    NOT NULL,
    data_devolucao  DATE,
    CONSTRAINT ck_data_prevista CHECK (data_prevista >= data_emprestimo),
    CONSTRAINT ck_data_devolucao CHECK (data_devolucao IS NULL OR data_devolucao >= data_emprestimo)
);
